import { fileURLToPath, URL } from 'node:url'

import fs from 'fs'
import { defineConfig, lazyPlugins } from 'vite-plus'
import tailwindcss from '@tailwindcss/vite'
import Vue from '@vitejs/plugin-vue'
import Press, { matter } from 'vite-plugin-press'
import Components from 'unplugin-vue-components/vite'
import VueRouter from 'unplugin-vue-router/vite'
import Layouts from 'vite-plugin-vue-layouts-next'
import Markdown from 'unplugin-vue-markdown/vite'
import svgLoader from 'vite-svg-loader'
import type MarkdownIt from 'markdown-it'
import configureMarkdown from './vite.config.markdown'

const target = process.env.ASPNETCORE_HTTPS_PORT
    ? `https://localhost:${process.env.ASPNETCORE_HTTPS_PORT}`
    : process.env.ASPNETCORE_URLS
      ? process.env.ASPNETCORE_URLS.split(';')[0]
      : 'https://localhost:5001'

const isProd = process.env.NODE_ENV === 'production'
const buildLocal = process.env.MODE === 'local'

// Define DEPLOY_API first
const DEPLOY_API = process.env.KAMAL_DEPLOY_HOST ? `https://${process.env.KAMAL_DEPLOY_HOST}` : target

// Now use it for API_URL
const API_URL = isProd ? DEPLOY_API : buildLocal ? '' : target

// Generated by `npm run dtos`, unplugin-vue-router and unplugin-vue-components, never lint or format
const generated = ['src/lib/dtos.ts', 'src/typed-router.d.ts', 'typed-router.d.ts', 'components.d.ts']
// Build output, vendored libs in public/ and markdown content
const content = ['dist/**', 'public/**', 'src/**/*.md']

// https://vite.dev/config/
export default defineConfig({
    define: { apiBaseUrl: `"${API_URL}"` },
    // lazyPlugins skips loading plugins for `vp check/lint/fmt`
    plugins: lazyPlugins(() => [
        // https://github.com/posva/unplugin-vue-router
        VueRouter({
            extensions: ['.vue', '.md'],
            dts: 'src/typed-router.d.ts',
            extendRoute(route) {
                const filePath = route.components.get('default')
                if (filePath && filePath.endsWith('.md')) {
                    const md = fs.readFileSync(filePath, 'utf-8')
                    const { attributes: frontmatter } = matter(md)
                    const pos = filePath.indexOf('/src/pages/')
                    const crumbs = filePath
                        .substring(pos + '/src/pages/'.length)
                        .split('/')
                        .slice(0, -1)
                        .map((name: string) => ({ name, href: `/${name}` }))
                    route.meta = Object.assign(route.meta || {}, { crumbs, frontmatter })
                }
            },
        }),
        Vue({
            include: [/\.vue$/, /\.md$/],
        }),
        tailwindcss(),

        Press({
            baseUrl: API_URL,
            metadataPath: 'public/api',
        }),
        Layouts(),
        svgLoader(),

        // https://github.com/unplugin/unplugin-vue-markdown
        Markdown({
            // default options passed to markdown-it
            // see: https://markdown-it.github.io/markdown-it/
            markdownItOptions: {
                html: true,
                linkify: true,
                typographer: true,
            },
            wrapperComponent: 'MarkdownPage',
            headEnabled: true,
            markdownItSetup(md) {
                configureMarkdown(md as MarkdownIt)
            },
        }),

        // https://github.com/unplugin/unplugin-vue-components
        Components({
            // allow auto load markdown components under `./src/components/`
            extensions: ['vue', 'md'],

            // allow auto import and register components used in markdown
            include: [/\.vue$/, /\.vue\?vue/, /\.md$/],

            //dts: 'src/components.d.ts',
            dts: true,
        }),
    ]),
    resolve: {
        alias: {
            '@': fileURLToPath(new URL('./src', import.meta.url)),
        },
    },
    build: {
        target: 'baseline-widely-available',
    },
    server: {
        host: true, // Listen on all interfaces (both IPv4 and IPv6)
        open: false,
    },
    test: {
        environment: 'happy-dom',
        globals: true,
        include: ['src/**/*.test.ts'],
    },
    lint: {
        ignorePatterns: [...content, ...generated],
        plugins: ['oxc', 'typescript', 'unicorn', 'vue'],
        categories: {
            correctness: 'error', // ~ eslint:recommended
        },
        env: { browser: true, builtin: true },
        rules: {
            // typescript-eslint recommended
            'typescript/ban-ts-comment': 'error',
            'typescript/no-duplicate-enum-values': 'error',
            'typescript/no-empty-object-type': 'error',
            'typescript/no-explicit-any': 'warn', // never enforced, ESLint 9 didn't load .eslintrc.cjs
            'typescript/no-extra-non-null-assertion': 'error',
            'typescript/no-misused-new': 'error',
            'typescript/no-namespace': 'error',
            'typescript/no-non-null-asserted-optional-chain': 'error',
            'typescript/no-require-imports': 'error',
            'typescript/no-this-alias': 'error',
            'typescript/no-unnecessary-type-constraint': 'error',
            'typescript/no-unsafe-declaration-merging': 'error',
            'typescript/no-unsafe-function-type': 'error',
            'typescript/no-wrapper-object-types': 'error',
            'typescript/prefer-as-const': 'error',
            'typescript/prefer-namespace-keyword': 'error',
            'typescript/triple-slash-reference': 'error',
            // type-aware rules no previous linter ran, keep visible but non-blocking
            'typescript/no-floating-promises': 'warn',
        },
        options: {
            typeAware: true,
            typeCheck: true, // .ts files only, `vue-tsc -b` type checks .vue SFCs
        },
    },
    fmt: {
        semi: false,
        singleQuote: true,
        tabWidth: 4,
        printWidth: 160,
        ignorePatterns: [...content, ...generated],
        overrides: [
            { files: ['**/*.json'], options: { tabWidth: 2 } }, // match npm's package.json indent
        ],
    },
})
